# Пример программы на Ruby для анализа метрик Холстеда.
# Вычисление Y = sin(X) через разложение функции в бесконечный ряд
#   Y = X - X^3/3! + X^5/5! - X^7/7! + ...
# с точностью eps = 0.0001
# (аналог Примера 1 из методических указаний, где программа была на Паскале)

eps = 0.0001
print "Введите X: "
x = gets.to_f

y = x          # начальные установки
n = 2
vs = x

begin
  vs = -vs * x * x / (2 * n - 1) / (2 * n - 2)   # формирование слагаемого
  n = n + 1
  y = y + vs
end while vs.abs > eps                            # выход из цикла по условию

puts "X = #{x}, Y = #{y}, eps = #{eps}"
